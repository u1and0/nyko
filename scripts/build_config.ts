// ホスト環境変数の書き込み
// Usage: deno task gen:config -- <HOST> <PORT> [STAGE]
const host = Deno.args[0];
const port = Deno.args[1];
const stage = Deno.args[2] ?? "manager";

const VALID_STAGE = ["manager", "requestor"] as const;
if (!VALID_STAGE.includes(stage as typeof VALID_STAGE[number])) {
  console.error(
    `Invalid STAGE: "${stage}". Must be one of: ${VALID_STAGE.join(", ")}`,
  );
  Deno.exit(1);
}

if (!host || !port) {
  console.error("Usage: deno task gen:config -- <HOST> <PORT> [STAGE]");
  Deno.exit(1);
}

const out = `// AUTO-GENERATED by scripts/build_config.ts — 直接編集禁止
export const NYKO_UPLOAD_HOST = "http://${host}:${port}";
export const NYKO_STAGE: "manager" | "requestor" = "${stage}";
`;

await Deno.writeTextFile("./dist/config.ts", out);
console.log(`config.ts generated: host=${host}, port=${port}, stage=${stage}`);
