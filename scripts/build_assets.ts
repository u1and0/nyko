// 配信用HTMLの構築
// executed by `deno task gen:assets`
// index.html / style.css / dist/script.js

const html = await Deno.readTextFile("static/index.html");
const css = await Deno.readTextFile("static/style.css");
const js = await Deno.readTextFile("dist/script.js");
const faviconBytes = await Deno.readFile("static/favicon.ico");
const faviconBase64 = btoa(String.fromCharCode(...faviconBytes));

const out = `  // AUTO-GENERATED by scripts/build_assets.ts : 直接編集禁止
export const indexHtml: string = ${JSON.stringify(html)}
export const styleCss: string = ${JSON.stringify(css)}
export const scriptJs: string = ${JSON.stringify(js)}
export const faviconBase64: string = ${JSON.stringify(faviconBase64)}
`;

await Deno.writeTextFile("./dist/assets.ts", out);
